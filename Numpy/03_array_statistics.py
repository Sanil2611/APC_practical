# Problem Statement:
# Create a NumPy array containing 10 numbers. Find and display the maximum,
# minimum, sum, and average of the elements.

import numpy as np

arr = np.array([12, 25, 8, 45, 30, 18, 50, 22, 15, 35])

print("Maximum:", np.max(arr))
print("Minimum:", np.min(arr))
print("Sum:", np.sum(arr))
print("Average:", np.mean(arr))
